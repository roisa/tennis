/**
 * Generates supabase/seed.sql from the TypeScript seed (single source of truth).
 * Usage: npm run db:seed-sql
 */
import fs from "node:fs";
import path from "node:path";
import { buildSeed } from "../src/lib/seed";
import type { TableName } from "../src/lib/data/schema";

const ORDER: TableName[] = ["destinations", "venues", "courts", "facilities", "reviews", "venue_sources", "venue_images", "articles", "videos", "guides"];
const SKIP = new Set(["overall_score"]);

function lit(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replace(/'/g, "''")}'`;
}

const db = buildSeed();
let sql = "-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.\n-- Research candidates: see verification_notes and venue_sources for provenance.\nbegin;\n\n";
for (const t of ORDER) {
  const rows = db[t] as Record<string, unknown>[];
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]).filter((c) => !SKIP.has(c));
  sql += `insert into public.${t} (${cols.join(", ")}) values\n`;
  sql += rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  sql += `\non conflict (id) do nothing;\n\n`;
}
sql += "commit;\n";
const out = path.join(process.cwd(), "supabase", "seed.sql");
fs.writeFileSync(out, sql);
console.log(`Wrote ${out}`);
